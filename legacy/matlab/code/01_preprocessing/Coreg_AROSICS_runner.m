%% Coreg_AROSICS_runner.m
% ============================================================
% PHASE 1 - Co-registration via AROSICS (Python)
%
% This script:
%   1. Writes the per-session Python co-registration script
%   2. Calls it via system() using the 'coreg' conda environment
%   3. Verifies outputs exist
%   4. Reports which images were corrected and by how much
%
% PREREQUISITE:
%   conda create -n coreg python=3.11
%   conda activate coreg
%   conda install -c conda-forge arosics shapely pyproj
%
% OUTPUTS -> OUT_DIR/Phase1_Coreg/run_YYYYMMDD_HHMMSS/
%   <date>_3B_AnalyticMS_SR_8b_coreg.tif   corrected images
%   coreg_report.csv                         per-image shift table
%   coreg_report.txt                         full text report
% ============================================================

clear; clc;
runTime      = datetime('now','TimeZone','local');
runTimestamp = char(runTime,'yyyyMMdd_HHmmss');
fprintf('Coreg_AROSICS_runner.m - Phase 1 - %s\n\n', runTimestamp);

%% Load shared config
global PIPELINE_CONFIG_PATH;
cfgPath = '';
if ~isempty(PIPELINE_CONFIG_PATH) && exist(PIPELINE_CONFIG_PATH,'file')
    cfgPath = PIPELINE_CONFIG_PATH;
else
    candidates = {fullfile(pwd,'pipeline_config.mat')};
    for k=1:numel(candidates)
        if exist(candidates{k},'file'), cfgPath=candidates{k}; break; end
    end
end
if isempty(cfgPath)
    [f,d]=uigetfile('pipeline_config.mat','Select pipeline_config.mat');
    if isequal(f,0), error('No config file selected.'); end
    cfgPath=fullfile(d,f);
end
cfg = load(cfgPath);

inDir   = cfg.RAW_DIR;
outBase = fullfile(cfg.OUT_DIR, 'Phase1_Coreg');
outDir  = fullfile(outBase, ['run_' runTimestamp]);
mkdir(outDir);

%% Settings
CONDA_ENV      = 'coreg';           % conda environment name with AROSICS
BAND_MATCH     = cfg.BANDS.NIR;    % band for matching (NIR=8, 1-based)
MAX_SHIFT_PX   = 10;               % maximum expected offset in pixels
WINDOW_SIZE    = '[128, 128]';     % smaller window - forces focus on island features
USE_LOCAL      = false;            % false=global, true=local warping
GRID_RES       = 100;              % local mode: tie-point grid spacing (px)
MIN_RELIABILITY= 60;               % local mode: minimum reliability %

% Island + reef study area mask (GeoJSON, WGS84)
% Restricts AROSICS tie-point search to the island/reef area only.
% Without this, AROSICS tries to match across the full scene (90% ocean)
% and finds no tie points, returning NaN shifts for all dates.
ISLAND_MASK_PATH = fullfile(cfg.ACA_DIR, 'GeoFeature.geojson');
if ~exist(ISLAND_MASK_PATH,'file')
    warning('GeoFeature.geojson not found at %s - AROSICS will use full scene.', ...
        ISLAND_MASK_PATH);
    ISLAND_MASK_PATH = '';
end

%% Find reference image
ff = dir(fullfile(inDir, cfg.RAW_PATTERN));
if isempty(ff), error('No SR files found in %s', inDir); end

refPath = '';
for i = 1:numel(ff)
    if contains(ff(i).name, cfg.REF_DATE)
        refPath = fullfile(ff(i).folder, ff(i).name);
        break;
    end
end
if isempty(refPath)
    error('Reference date %s not found in %s', cfg.REF_DATE, inDir);
end
fprintf('Reference: %s\n', refPath);
fprintf('Output:    %s\n\n', outDir);

%% Write Python script dynamically
pyScript = fullfile(outDir, 'run_arosics.py');

pyLines = {
    '#!/usr/bin/env python3'
    '"""'
    'Auto-generated AROSICS co-registration script.'
    sprintf('Generated by Coreg_AROSICS_runner.m - %s', runTimestamp)
    '"""'
    'import os, sys, glob, shutil, traceback, math'
    'from datetime import datetime'
    'from pathlib import Path'
    'import pandas as pd'
    'import numpy as np'
    'try:'
    '    from arosics import COREG, COREG_LOCAL'
    'except ImportError:'
    '    print("ERROR: AROSICS not installed. Run: conda install -c conda-forge arosics")'
    '    sys.exit(1)'
    ''
    sprintf('IN_DIR      = r"%s"', inDir)
    sprintf('OUT_DIR     = r"%s"', outDir)
    sprintf('REF_PATH    = r"%s"', refPath)
    sprintf('PAT         = "%s"', cfg.RAW_PATTERN)
    sprintf('BAND_MATCH  = %d', BAND_MATCH)
    sprintf('MAX_SHIFT   = %d', MAX_SHIFT_PX)
    sprintf('WIN_SIZE    = %s', WINDOW_SIZE)
    sprintf('USE_LOCAL   = %s', iif(USE_LOCAL,'True','False'))
    sprintf('GRID_RES    = %d', GRID_RES)
    sprintf('MIN_REL     = %d', MIN_RELIABILITY)
    ''
    '# Find all SR files'
    'all_files = sorted(Path(IN_DIR).glob(PAT.replace("*","**").replace("**","*")))'
    'if not all_files:'
    '    all_files = sorted(Path(IN_DIR).glob(PAT))'
    'print(f"Found {len(all_files)} SR files.")'
    ''
    'def strip_statistics_metadata(tif_path):'
    '    """Strip STATISTICS_APPROXIMATE metadata tags that cause AROSICS band-count mismatch."""'
    '    try:'
    '        from osgeo import gdal'
    '        gdal.UseExceptions()'
    '        ds = gdal.Open(str(tif_path), gdal.GA_Update)'
    '        if ds is None:'
    '            return False'
    '        stripped = False'
    '        for bi in range(1, ds.RasterCount + 1):'
    '            band = ds.GetRasterBand(bi)'
    '            md = band.GetMetadata()'
    '            for stat_key in list(md.keys()):'
    '                if stat_key.startswith("STATISTICS_"):'
    '                    band.SetMetadataItem(stat_key, None)'
    '                    stripped = True'
    '        if stripped:'
    '            ds.FlushCache()'
    '        ds = None'
    '        return stripped'
    '    except Exception as e:'
    '        print(f"    strip_metadata warning: {e}")'
    '        return False'
    ''
    'results = []'
    'for tgt_path in all_files:'
    '    out_path = Path(OUT_DIR) / tgt_path.name.replace(".tif","_coreg.tif")'
    '    print(f"\n{tgt_path.name}")'
    '    # Reference copies itself'
    '    if str(tgt_path.resolve()) == str(Path(REF_PATH).resolve()):'
    '        print("  REFERENCE - copying as-is")'
    '        shutil.copy2(tgt_path, out_path)'
    '        results.append({"file":tgt_path.name,"status":"REF",'
    '            "x_shift_px":0,"y_shift_px":0,"x_shift_m":0,"y_shift_m":0,'
    '            "reliability":100,"output":out_path.name,"notes":"reference"})'
    '        continue'
    '    try:'
    '        t0 = datetime.now()'
    '        # Strip problematic STATISTICS_APPROXIMATE metadata before COREG init'
    '        stripped = strip_statistics_metadata(tgt_path)'
    '        if stripped:'
    '            print(f"  Stripped STATISTICS_APPROXIMATE metadata tag")'
    '        if not USE_LOCAL:'
    '            # Build kwargs'
    '            coreg_kwargs = dict('
    '                path_out=str(out_path), fmt_out="GTiff",'
    '                r_b4match=BAND_MATCH, s_b4match=BAND_MATCH,'
    '                ws=WIN_SIZE, max_shift=MAX_SHIFT,'
    '                align_grids=True, match_gsd=False,'
    '                resamp_alg_deshift="cubic",'
    '                v=False, q=False, ignore_errors=True)'
    sprintf('            mask_path = r"%s"', ISLAND_MASK_PATH)
    '            if mask_path and os.path.exists(mask_path):'
    '                import json'
    '                from shapely.geometry import shape'
    '                from shapely.ops import unary_union, transform'
    '                import pyproj'
    '                with open(mask_path) as f:'
    '                    gj = json.load(f)'
    '                geoms = [shape(feat["geometry"]) for feat in gj["features"] if feat.get("properties",{}).get("Class") == "Island"]'
    '                combined_wgs84 = unary_union(geoms)'
    '                proj_wgs84 = pyproj.CRS("EPSG:4326")'
    '                proj_utm47 = pyproj.CRS("EPSG:32647")'
    '                transformer = pyproj.Transformer.from_crs('
    '                    proj_wgs84, proj_utm47, always_xy=True)'
    '                combined_utm = transform(transformer.transform, combined_wgs84)'
    '                coreg_kwargs["footprint_poly_ref"] = combined_utm.wkt'
    '                coreg_kwargs["footprint_poly_tgt"] = combined_utm.wkt'
    '                print(f"  Using island mask (UTM47N): bounds={combined_utm.bounds}")'
    '            CR = COREG(REF_PATH, str(tgt_path), **coreg_kwargs)'
    '            CR.calculate_spatial_shifts()'
    '            xpx = CR.x_shift_px if hasattr(CR,"x_shift_px") else float("nan")'
    '            ypx = CR.y_shift_px if hasattr(CR,"y_shift_px") else float("nan")'
    '            rel = CR.shift_reliability if hasattr(CR,"shift_reliability") else float("nan")'
    '            print(f"  Detected shift: X={xpx:+.3f}px Y={ypx:+.3f}px rel={rel:.1f}%")'
    '            CR.correct_shifts()'
    '            xm = CR.x_shift_m if hasattr(CR,"x_shift_m") else xpx * 3.0'
    '            ym = CR.y_shift_m if hasattr(CR,"y_shift_m") else ypx * 3.0'
    '            print(f"  Applied shift : X={xm:+.2f}m Y={ym:+.2f}m")'
    '        else:'
    '            proj_dir = Path(OUT_DIR) / "local_proj" / tgt_path.stem'
    '            CRL = COREG_LOCAL(REF_PATH, str(tgt_path),'
    '                grid_res=GRID_RES, window_size=WIN_SIZE,'
    '                path_out=str(out_path), fmt_out="GTiff",'
    '                projectDir=str(proj_dir),'
    '                r_b4match=BAND_MATCH, s_b4match=BAND_MATCH,'
    '                max_shift=MAX_SHIFT,'
    '                tieP_filter_level=3, min_reliability=MIN_REL,'
    '                align_grids=True,'
    '                resamp_alg_deshift="cubic",'
    '                CPUs=None, v=False, q=False, ignore_errors=True)'
    '            CRL.correct_shifts()'
    '            tp = CRL.CoRegPoints_table'
    '            valid = tp[tp.get("OUTLIER",pd.Series([False]*len(tp)))==False]'
    '            xpx=float("nan"); ypx=float("nan")'
    '            xm=valid["ABS_SHIFT"].mean() if len(valid) else float("nan")'
    '            ym=float("nan"); rel=float("nan")'
    '            print(f"  Local: {len(valid)} tie-points  mean_shift={xm:.2f}m")'
    '        elapsed=(datetime.now()-t0).total_seconds()'
    '        results.append({"file":tgt_path.name,"status":"OK",'
    '            "x_shift_px":round(xpx,4),"y_shift_px":round(ypx,4),'
    '            "x_shift_m":round(xm,3),"y_shift_m":round(ym,3),'
    '            "reliability":rel,"output":out_path.name,'
    '            "notes":f"elapsed={elapsed:.1f}s"})'
    '    except Exception as e:'
    '        print(f"  ERROR: {e}")'
    '        traceback.print_exc()'
    '        shutil.copy2(tgt_path, out_path)'
    '        results.append({"file":tgt_path.name,"status":"ERROR",'
    '            "x_shift_px":float("nan"),"y_shift_px":float("nan"),'
    '            "x_shift_m":float("nan"),"y_shift_m":float("nan"),'
    '            "reliability":float("nan"),"output":out_path.name,"notes":str(e)})'
    ''
    '#  Median-shift fallback for NaN/ERROR dates '
    '# If AROSICS failed to find tie points (shift=NaN) or errored, apply the'
    '# median of all successfully detected shifts as a proxy correction.'
    '# This handles dates like 20230519 where waves/haze prevent tie-point matching.'
    'df = pd.DataFrame(results)'
    'ok_mask = (df["status"] == "OK") & df["x_shift_px"].notna() & df["y_shift_px"].notna()'
    'ok_mask = ok_mask & (df["x_shift_px"] != 0) & (df["y_shift_px"] != 0)'
    'if ok_mask.sum() >= 3:'
    '    med_x = df.loc[ok_mask, "x_shift_px"].median()'
    '    med_y = df.loc[ok_mask, "y_shift_px"].median()'
    '    print(f"\nMedian shift from {ok_mask.sum()} good dates: X={med_x:+.3f}px Y={med_y:+.3f}px")'
    '    from arosics import COREG'
    '    for idx, row in df.iterrows():'
    '        needs_fallback = (row["status"] in ("ERROR","NaN_SHIFT")) or \'
    '                         (row["status"] == "OK" and \'
    '                          (math.isnan(float(row["x_shift_px"])) or \'
    '                           math.isnan(float(row["y_shift_px"]))))'
    '        if not needs_fallback and row["status"] == "OK":'
    '            xv = float(row["x_shift_px"])'
    '            yv = float(row["y_shift_px"])'
    '            needs_fallback = math.isnan(xv) or math.isnan(yv)'
    '        if not needs_fallback:'
    '            continue'
    '        fname = row["file"]'
    '        tgt_path = Path(IN_DIR) / fname'
    '        out_path = Path(OUT_DIR) / fname.replace(".tif","_coreg.tif")'
    '        print(f"\n  FALLBACK {fname}")'
    '        print(f"  Applying median shift X={med_x:+.3f}px Y={med_y:+.3f}px")'
    '        try:'
    '            strip_statistics_metadata(tgt_path)'
    '            fb_kwargs = dict('
    '                path_out=str(out_path), fmt_out="GTiff",'
    '                r_b4match=BAND_MATCH, s_b4match=BAND_MATCH,'
    '                ws=WIN_SIZE, max_shift=MAX_SHIFT,'
    '                align_grids=True, match_gsd=False,'
    '                resamp_alg_deshift="cubic",'
    '                v=False, q=False, ignore_errors=True)'
    '            CR_fb = COREG(REF_PATH, str(tgt_path), **fb_kwargs)'
    '            # Force the detected shift to median values'
    '            CR_fb.x_shift_px = med_x'
    '            CR_fb.y_shift_px = med_y'
    '            CR_fb.correct_shifts()'
    '            df.at[idx, "x_shift_px"] = med_x'
    '            df.at[idx, "y_shift_px"] = med_y'
    '            df.at[idx, "status"]     = "FALLBACK"'
    '            df.at[idx, "notes"]      = f"median_fallback X={med_x:+.3f} Y={med_y:+.3f}"'
    '            df.at[idx, "output"]     = out_path.name'
    '            print(f"  FALLBACK applied - {out_path.name}")'
    '        except Exception as e2:'
    '            print(f"  FALLBACK ERROR: {e2}")'
    '            df.at[idx, "notes"] = f"fallback_error: {e2}"'
    'else:'
    '    print(f"\nToo few good dates ({ok_mask.sum()}) for median fallback - skipping")'
    ''
    '# Save final report'
    'report_csv = str(Path(OUT_DIR) / "coreg_report.csv")'
    'df.to_csv(report_csv, index=False)'
    'print(f"Report saved: {report_csv}")'
    'n_ok  = len(df[df["status"].isin(["OK","REF"])])'
    'n_fb  = len(df[df["status"]=="FALLBACK"])'
    'n_err = len(df[df["status"]=="ERROR"])'
    'print(f"Done. OK={n_ok}  FALLBACK={n_fb}  ERROR={n_err}")'
};

fid = fopen(pyScript,'w');
for k=1:numel(pyLines)
    fprintf(fid,'%s\n', pyLines{k});
end
fclose(fid);
fprintf('Python script written: %s\n', pyScript);

%% Detect conda/Python executable
fprintf('\nDetecting Python environment...\n');
condaBase = detectCondaBase();
if isempty(condaBase)
    fprintf('WARNING: conda not auto-detected. Trying direct python call.\n');
    pythonCmd = 'python';
else
    if ispc
        pythonCmd = sprintf('"%s\\Scripts\\conda.exe" run -n %s python', condaBase, CONDA_ENV);
    else
        pythonCmd = sprintf('"%s/bin/conda" run -n %s python', condaBase, CONDA_ENV);
    end
