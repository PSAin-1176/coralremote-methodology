%% LOCAL FUNCTIONS

function base = detectCondaBase()
    base = '';
    % Try conda info
    [s,o] = system('conda info --base 2>&1');
    if s==0 && ~contains(o,'not found') && ~contains(o,'error')
        base = strtrim(o);
        return;
    end
    % Common locations
    candidates = {};
    if ispc
        candidates = {fullfile(getenv('USERPROFILE'),'anaconda3'),...
                      fullfile(getenv('USERPROFILE'),'miniconda3'),...
                      'C:\ProgramData\anaconda3',...
                      'C:\ProgramData\miniconda3'};
    else
        candidates = {fullfile(getenv('HOME'),'anaconda3'),...
                      fullfile(getenv('HOME'),'miniconda3'),...
                      '/opt/anaconda3','/opt/miniconda3'};
    end
    for k=1:numel(candidates)
        if exist(candidates{k},'dir')
            base = candidates{k};
            return;
        end
    end
end

function v = iif(cond, a, b)
    if cond, v=a; else, v=b; end
end
