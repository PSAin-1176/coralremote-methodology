fprintf('%-55s  %-6s  %8s  %8s  %9s\n','File','Status','X(px)','Y(px)','|shift|(m)');
fprintf('%s\n', repmat('-',1,90));
nOK=0; nErr=0;
for k=1:numel(rows)
    r = rows{k};
    if numel(r) < 6, continue; end
    fname  = r{1};
    st     = r{2};
    xpx    = str2double(r{3});
    ypx    = str2double(r{4});
    xm     = str2double(r{5});
    ym     = str2double(r{6});
    magm   = sqrt(xm^2+ym^2);
    fprintf('%-55s  %-6s  %8.3f  %8.3f  %9.2f\n', fname, st, xpx, ypx, magm);
    if strcmp(st,'OK'), nOK=nOK+1; end
    if strcmp(st,'ERROR'), nErr=nErr+1; end
end

